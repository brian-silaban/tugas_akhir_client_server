    {
        $categories = $this->getStaticCategories();
        $destinations = $this->getStaticDestinations();
        $partnerEcosystem = $this->getStaticPartnerEcosystem();

        // Ambil parameter filter opsional dari query string (?q=...&city=...&category=...&max_price=...)
