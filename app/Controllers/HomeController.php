            'q'         => trim((string) $this->request->getGet('q')),
            'city'      => trim((string) $this->request->getGet('city')),
            'category'  => trim((string) $this->request->getGet('category')),
            'max_price' => trim((string) $this->request->getGet('max_price')),
        ];

        $cities = array_values(array_unique(array_column($destinations, 'city')));

        return view('pages/home', [
            'pageTitle'        => 'IndWalk — Direktori Kurasi & Eksplorasi Wisata Nusantara',
            'metaDescription'  => 'Direktori kurasi destinasi wisata Indonesia dengan transparansi harga tiket, jam operasional, titik koordinat, dan integrasi ekosistem perjalanan Client-Server.',
            'categories'       => $categories,
            'destinations'     => $destinations,
            'cities'           => $cities,
            'partnerEcosystem' => $partnerEcosystem,
            'filters'          => $filters,
        ]);
    }

