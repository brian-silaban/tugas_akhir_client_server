    /**
     * Menampilkan halaman Beranda (/) IndWalk menggunakan data statis
     * yang selaras dengan tabel PostgreSQL pada IndWalkSeeder.php.
     */
    public function index(): string
    {
        // Mengambil data kategori, destinasi, dan simulasi REST API kelompok mitra
        $daftarKategori  = $this->ambilKategoriStatis();
        $daftarDestinasi = $this->ambilDestinasiStatis();
        $ekosistemMitra  = $this->ambilEkosistemMitraStatis();

        // Mengambil parameter filter pencarian dari URL (?kata_kunci=...&kota=...&kategori=...&harga_maksimal=...)
        $filterPencarian = [
            'kata_kunci'     => trim((string) $this->request->getGet('kata_kunci')),
            'kota'           => trim((string) $this->request->getGet('kota')),
            'kategori'       => trim((string) $this->request->getGet('kategori')),
            'harga_maksimal' => trim((string) $this->request->getGet('harga_maksimal')),
        ];

        // Mengambil daftar nama kota unik dari daftar destinasi
        $kolomKota  = array_column($daftarDestinasi, 'kota');
        $daftarKota = array_values(array_unique($kolomKota));

        $dataTampilan = [
            'judulHalaman'    => 'IndWalk — Direktori Kurasi & Eksplorasi Wisata Nusantara',
            'deskripsiMeta'   => 'Direktori kurasi destinasi wisata Indonesia dengan transparansi harga tiket, jam operasional, titik koordinat, dan integrasi ekosistem perjalanan Client-Server.',
            'daftarKategori'  => $daftarKategori,
            'daftarDestinasi' => $daftarDestinasi,
            'daftarKota'      => $daftarKota,
            'ekosistemMitra'  => $ekosistemMitra,
            'filterPencarian' => $filterPencarian,
        ];

        return view('pages/home', $dataTampilan);
    }

